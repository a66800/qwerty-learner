/**
 * MOBEI: export MOBEI Words' word lists as Qwerty Learner dictionaries.
 *
 *   node scripts/mobei-words-dicts.mjs [path\to\mobei-words\dist]
 *
 * - One dictionary per CEFR level (A1–C1) plus US Essentials, in Words' order.
 * - "trans" is Words' own 核心理解: the core idea when Words has one, otherwise
 *   Words' Chinese meaning. Qwerty Learner's translations are never used.
 * - US IPA from Words. Writes public/dicts/mobei-words-*.json and
 *   src/mobei/mobeiDicts.ts (the registry entries). Rerun after Words changes.
 */
import { loadWords } from './mobei-load-words.mjs'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const wordsDist = process.argv[2] || 'D:/dev/mobei-words/dist'
const run = loadWords(wordsDist)

const raw = JSON.parse(
  run(`JSON.stringify((()=>{
    const pick = x => {
      const c = coreFor(x)
      const ideas = c ? (c.short ? [c.short] : (c.ideas || []).slice(0, c.separate ? 2 : 1)) : []
      return { id: x.id, word: x.word, ipa: x.ipa || '', cefr: x.cefr, meaning: x.meaning || '', core: ideas }
    }
    return { official: official.filter(isComplete).map(pick), us: usSupplement.filter(isComplete).map(pick) }
  })())`),
)

/** "/ə, eɪ/ · /ən, æn/" → "ə, eɪ" (first form only, matching the first headword variant) */
const cleanIpa = (ipa) =>
  String(ipa)
    .split(/\s*·\s*/)[0]
    .trim()
    .replace(/^\/|\/$/g, '')
    .trim()
/**
 * Typing needs a plain headword: "a, an" → "a", "can¹" → "can", "last 1 (final)" → "last",
 * "colour (BrE)" → "colour". Entries that still contain symbols or digits (AT&T, 911) are skipped.
 */
function headword(word) {
  let w = String(word).trim().replace(/[’‘]/g, "'")
  w = w.replace(/\s*\(.*?\)\s*/g, ' ')
  w = w.split(/\s*[,;／/]\s*/)[0]
  w = w
    .replace(/[¹²³⁴⁵⁶⁷⁸⁹⁰]/g, '')
    .replace(/\s+\d+\s*$/, '')
    .trim()
  return /^[A-Za-z][A-Za-z' .-]*[A-Za-z.]$|^[A-Za-z]$/.test(w) ? w : null
}

function toEntries(items) {
  const seen = new Set()
  const out = []
  const skipped = []
  for (const x of items) {
    const name = headword(x.word)
    if (!name) {
      skipped.push(x.word)
      continue
    }
    const key = `${name.toLowerCase()}|${x.meaning}`
    if (seen.has(key)) continue
    seen.add(key)
    const trans = x.core.length ? x.core : [x.meaning]
    const phone = cleanIpa(x.ipa)
    out.push({ name, trans: trans.filter(Boolean), usphone: phone, ukphone: phone })
  }
  return { out, skipped }
}

const groups = [
  ...['A1', 'A2', 'B1', 'B2', 'C1'].map((lv) => ({
    id: `mobei-words-${lv.toLowerCase()}`,
    name: `Words ${lv}`,
    description: `MOBEI Words ${lv} 级词表，配 Words 的核心理解`,
    tags: ['CEFR 分级'],
    items: raw.official.filter((x) => x.cefr === lv),
  })),
  {
    id: 'mobei-words-us',
    name: 'Words 美国生活',
    description: 'MOBEI Words 美国生活专题（US Essentials），配 Words 的核心理解',
    tags: ['美国生活'],
    items: raw.us,
  },
]

const registry = []
for (const g of groups) {
  const { out, skipped } = toEntries(g.items)
  const file = `${g.id}.json`
  fs.writeFileSync(path.join(root, 'public', 'dicts', file), JSON.stringify(out, null, 1) + '\n')
  registry.push({
    id: g.id,
    name: g.name,
    description: g.description,
    category: 'MOBEI Words',
    tags: g.tags,
    url: `/dicts/${file}`,
    length: out.length,
    language: 'en',
    languageCategory: 'en',
  })
  console.log(`${g.id}: ${out.length} words${skipped.length ? `, skipped ${skipped.length}: ${skipped.slice(0, 8).join(' | ')}` : ''}`)
}

const ts = `// Generated by scripts/mobei-words-dicts.mjs from MOBEI Words — do not edit by hand.
import type { DictionaryResource } from '@/typings'

export const mobeiWordsDicts: DictionaryResource[] = ${JSON.stringify(registry, null, 2)}
`
fs.writeFileSync(path.join(root, 'src', 'mobei', 'mobeiDicts.ts'), ts)
console.log('registry written: src/mobei/mobeiDicts.ts')
